import os
import shutil
from pathlib import Path

import cocotb_test.simulator

import open_eye.test_utils_main as ptu
import open_eye.vh_file_creator as vh_creator
import open_eye.generator as generator

from open_eye import hdl_dir


def test_attention_projection_openeye_top():

    root = Path(__file__).resolve().parents[2]
    test_dir = Path(__file__).resolve().parent

    build_dir = test_dir / ".sim_build_projection_openeye"
    build_dir.mkdir(parents=True, exist_ok=True)

    # Match the configuration of the original Attention test
    config = {
        "CLUSTER_ROWS": "2",
        "CLUSTER_COLUMNS": "2",
        "NUM_GLB_IACT": "3",
        "NUM_GLB_PSUM": "4",
        "NUM_GLB_WGHT": "3",
        "DATAFLOW": "output_stationary",
        "BRANCHES": "1",
        "BUFFER_WIDTH": "12",
        "QUANT_AMOUNT": "1024",
        "RAM_CELLS": "32",
    }

    os.environ.update(config)

    # Generate the exact OpenEye parameter headers
    vh_creator.create_vh_file_from_envvars(
        str(build_dir),
        str(hdl_dir) + os.sep,
        toplevel="OpenEye_FPGA"
    )

    # Generate the register-map decoder
    generator.create_regmap_params_vh_file(
        str(root / "test" / "cocotb_fpga"),
        str(build_dir),
        str(build_dir)
    )

    # Memory images generated by Attention Projection Mapper
    memory_dir = test_dir / "data" / "attention_mapper_v1"

    for filename in (
        "common_rom.mem",
        "activation_ram.mem",
        "weight_ram.mem",
    ):
        shutil.copyfile(
            memory_dir / filename,
            build_dir / filename
        )

    # Compile the actual OpenEye hardware sources
    sources = [
        src for src in ptu.get_verilog_sources(str(hdl_dir))
        if os.path.basename(src) != "dma_storage.v"
    ]

    # Use the decoder generated for this exact configuration
    sources.append(str(build_dir / "dma_storage.v"))

    cocotb_test.simulator.run(
        verilog_sources=sources,
        toplevel="attention_projection_openeye_top",
        module="attention_gemv_projection_openeye_tb",
        python_search=[str(test_dir)],
        sim_build=str(build_dir),
        simulator="icarus",
        defines={
            "NO_TRACE": "TRUE",
            "USE_INTERNAL_PARAMS_PE": "TRUE",
        },
        force_compile=True,
        waves=True,
    )