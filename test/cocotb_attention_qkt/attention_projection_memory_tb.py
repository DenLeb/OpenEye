"""Cocotb verification of ROM Template + RAM Override for all 12 GEMVs.

Checks every 64-bit word, selector latching, and the two RAM write ports.
Requires files generated by open_eye.attention_projection_mapper.
"""

import os
from pathlib import Path
import cocotb
from cocotb.clock import Clock
from cocotb.triggers import Timer, RisingEdge

DATA_DIR = Path(os.environ.get("ATTENTION_MEMORY_DATA_DIR", "test/cocotb_attention_qkt/data/attention_mapper_v1"))


def read_mem(filename):
    return [
        int(line.strip(), 16) 
        for line in (DATA_DIR / filename).read_text().splitlines() 
        if line.strip()]


async def wait_for_comb():
    await Timer(1, unit="ns")


@cocotb.test()
async def verify_all_projection_streams(dut):
    clock = Clock(dut.clk_i, 10, unit="ns")
    cocotb.start_soon(clock.start())

    dut.rst_ni.value = 0
    dut.start_i.value = 0
    dut.busy_i.value = 0
    dut.token_select_i.value = 0
    dut.projection_select_i.value = 0
    dut.addr_i.value = 0
    dut.iact_we_i.value = 0
    dut.iact_wr_addr_i.value = 0
    dut.iact_wr_data_i.value = 0
    dut.wght_we_i.value = 0
    dut.wght_wr_addr_i.value = 0
    dut.wght_wr_data_i.value = 0
    await RisingEdge(dut.clk_i)
    await Timer(1, unit="ns")
    dut.rst_ni.value = 1

    total_checked = 0
    for proj_id, kind in enumerate(("q", "k", "v")):
        for token in range(4):
            expected = read_mem(f"verification_streams/{kind}_t{token}.mem")
            assert len(expected) == 939

            # Submit operation while idle, then keep busy high during reading.
            await Timer(1, unit="ns")
            dut.projection_select_i.value = proj_id
            dut.token_select_i.value = token
            dut.busy_i.value = 0
            dut.start_i.value = 1
            await RisingEdge(dut.clk_i)
            await Timer(1, unit="ns")
            dut.start_i.value = 0
            dut.busy_i.value = 1

            # Deliberately perturb requests while busy: latched values must win.
            dut.projection_select_i.value = (proj_id + 1) % 3
            dut.token_select_i.value = (token + 1) % 4
            
            for addr, word in enumerate(expected):
                dut.addr_i.value = addr
                await wait_for_comb()
                got = int(dut.data_o.value)
                assert got == word, (
                    f"{kind}_t{token} addr={addr}: "
                    f"got 0x{got:016x}, expected 0x{word:016x}"
                )
                total_checked += 1

            dut.busy_i.value = 0
            dut.addr_i.value = 939
            await wait_for_comb()
            assert int(dut.data_o.value) == 0, "Invalid stream address must read as zero"

    # RAM writable ports: update one activation and one weight word,
    # reselect q_t0, and ensure only the relevant addresses read back changed data.
    dut.iact_we_i.value = 1
    dut.iact_wr_addr_i.value = 0
    dut.iact_wr_data_i.value = 0x0123456789ABCDEF
    dut.wght_we_i.value = 1
    dut.wght_wr_addr_i.value = 0
    dut.wght_wr_data_i.value = 0xFEDCBA9876543210
    await RisingEdge(dut.clk_i)
    await Timer(1, unit="ns")
    dut.iact_we_i.value = 0
    dut.wght_we_i.value = 0

    dut.token_select_i.value = 0
    dut.projection_select_i.value = 0
    dut.start_i.value = 1
    dut.busy_i.value = 0
    await RisingEdge(dut.clk_i)
    await Timer(1, unit="ns")
    dut.start_i.value = 0

    dut.addr_i.value = 19
    await wait_for_comb()
    assert int(dut.data_o.value) == 0x0123456789ABCDEF
    dut.addr_i.value = 27
    await wait_for_comb()
    assert int(dut.data_o.value) == 0xFEDCBA9876543210

    dut._log.info("PASS: %d DMA words across 12 Q/K/V streams; selectors latched; RAM writes verified", total_checked)
