`timescale 1ns / 1ps

//==============================================================
// Module: attention_gemv_openeye_top
//
// Purpose:
//   Connect the verified GEMV ROM/control path to OpenEye_FPGA.
//
// Top-level integration of the GEMV controller, DMA adapter, ROM banks,
// and the real OpenEye FPGA accelerator.
// Supports hardware-controlled GEMV execution with selectable input streams.
//==============================================================

module attention_projection_openeye_top #(
    parameter integer DMA_WIDTH  = 64,
    parameter integer ADDR_WIDTH = 16,
    parameter integer ROM_DEPTH  = 939
)(
    input  wire clk_i,
    input  wire rst_ni,
    input  wire start_i,
    input wire [1:0] token_select_i,
    input wire [1:0] projection_select_i,

    // Activation RAM write interface
    input wire                  iact_we_i,
    input wire [ADDR_WIDTH-1:0] iact_wr_addr_i,
    input wire [DMA_WIDTH-1:0]  iact_wr_data_i,

    // Weight RAM write interface
    input wire                  wght_we_i,
    input wire [ADDR_WIDTH-1:0] wght_wr_addr_i,
    input wire [DMA_WIDTH-1:0]  wght_wr_data_i,

    output wire busy_o,
    output wire adapter_busy_o,
    output wire done_o,

    // Result interface for verification
    output wire                 result_write_o,
    output wire [DMA_WIDTH-1:0] result_data_o,
    output wire [ADDR_WIDTH-1:0] result_addr_o,

    input wire [1:0] q_rd_token_i,
    input wire [2:0] q_rd_feature_i,

    input wire [1:0] k_rd_token_i,
    input wire [2:0] k_rd_feature_i,

    input wire [1:0] v_rd_token_i,
    input wire [2:0] v_rd_feature_i,

    output wire [19:0] q_data_o,
    output wire [19:0] k_data_o,
    output wire [19:0] v_data_o,

    // Quantization control interface
    input  wire quant_start_i,
    output wire quant_busy_o,
    output wire quant_done_o,

    // Quantized Q8 read interface
    input  wire [1:0] q8_rd_token_i,
    input  wire [2:0] q8_rd_feature_i,
    output wire signed [7:0] q8_data_o,

    // Quantized K8 read interface
    input  wire [1:0] k8_rd_token_i,
    input  wire [2:0] k8_rd_feature_i,
    output wire signed [7:0] k8_data_o,

    // Quantization scaling factors
    output wire [6:0] q_shift_o,
    output wire [6:0] k_shift_o,

    // Debug address
    output wire [ADDR_WIDTH-1:0] stream_addr_o
);

    //==========================================================
    // DMA connections between the adapter and OpenEye
    //==========================================================

    wire [DMA_WIDTH-1:0] dma_input_data;
    wire                 dma_input_valid;
    wire                 dma_input_ready;

    wire [DMA_WIDTH-1:0] dma_output_data;
    wire                 dma_output_valid;
    wire                 dma_output_last;
    wire                 dma_output_ready;
 
    //==========================================================
    // Start signals for the projection and quantization operations
    wire projection_start;
    wire quant_start;

    assign projection_start = start_i && !quant_busy_o;

    assign quant_start =
        quant_start_i &&
        !start_i &&
        !busy_o &&
        !adapter_busy_o &&
        !result_write_o;

    //==========================================================
    // Controller + DMA Adapter + ROM
    //==========================================================

    attention_projection_stream_top #(
        .DMA_WIDTH    (DMA_WIDTH),
        .ADDR_WIDTH   (ADDR_WIDTH),
        .STREAM_WORDS (ROM_DEPTH)
    ) u_attention_stream (

        .clk_i          (clk_i),
        .rst_ni         (rst_ni),
        .start_i        (projection_start),
        .token_select_i      (token_select_i),
        .projection_select_i (projection_select_i),

        .busy_o         (busy_o),
        .adapter_busy_o (adapter_busy_o),
        .done_o         (done_o),

        // Input DMA
        .dma_ready_i    (dma_input_ready),
        .dma_data_o     (dma_input_data),
        .dma_valid_o    (dma_input_valid),

        // Output DMA
        .dma_result_data_i  (dma_output_data),
        .dma_result_valid_i (dma_output_valid),
        .dma_result_last_i  (dma_output_last),
        .dma_result_ready_o (dma_output_ready),

        // Results
        .result_write_o (result_write_o),
        .result_data_o  (result_data_o),
        .result_addr_o  (result_addr_o),

        // Activation RAM write interface
        .iact_we_i       (iact_we_i),
        .iact_wr_addr_i  (iact_wr_addr_i),
        .iact_wr_data_i  (iact_wr_data_i),

        // Weight RAM write interface
        .wght_we_i       (wght_we_i),
        .wght_wr_addr_i  (wght_wr_addr_i),
        .wght_wr_data_i  (wght_wr_data_i),
        
        .stream_addr_o  (stream_addr_o)
    );

    // Read addresses generated by quantization controller
    wire [1:0] quant_q_rd_token;
    wire [2:0] quant_q_rd_feature;

    wire [1:0] quant_k_rd_token;
    wire [2:0] quant_k_rd_feature;

    // Address multiplexers
    wire [1:0] raw_q_rd_token;
    wire [2:0] raw_q_rd_feature;

    wire [1:0] raw_k_rd_token;
    wire [2:0] raw_k_rd_feature;

    assign raw_q_rd_token =
        quant_busy_o ? quant_q_rd_token : q_rd_token_i;

    assign raw_q_rd_feature =
        quant_busy_o ? quant_q_rd_feature : q_rd_feature_i;

    assign raw_k_rd_token =
        quant_busy_o ? quant_k_rd_token : k_rd_token_i;

    assign raw_k_rd_feature =
        quant_busy_o ? quant_k_rd_feature : k_rd_feature_i;

    //==========================================================
    // Q/K/V Projection Result Buffer
    //==========================================================

    attention_projection_result_buffer u_qkv_buffer (

        .clk_i              (clk_i),
        .rst_ni             (rst_ni),

        // Capture the selected operation
        .start_i            (projection_start),
        .token_select_i     (token_select_i),
        .projection_select_i(projection_select_i),

        // Receive calculated PSUM values
        .result_write_i     (result_write_o),
        .result_addr_i      (result_addr_o),
        .result_data_i      (result_data_o),

        .q_rd_token_i   (raw_q_rd_token),
        .q_rd_feature_i (raw_q_rd_feature),

        .k_rd_token_i   (raw_k_rd_token),
        .k_rd_feature_i (raw_k_rd_feature),

        .v_rd_token_i   (v_rd_token_i),
        .v_rd_feature_i (v_rd_feature_i),

        .q_data_o           (q_data_o),
        .k_data_o           (k_data_o),
        .v_data_o           (v_data_o)

    );

    //==========================================================
    // Q/K Quantization Controller
    //==========================================================

    attention_qk_quantization_controller #(
        .NUM_TOKENS   (4),
        .NUM_FEATURES (8),
        .DATA_WIDTH   (20),
        .SHIFT_WIDTH  (7)
    ) u_qk_quant_controller (

        .clk_i   (clk_i),
        .rst_ni  (rst_ni),

        // Control
        .start_i (quant_start),
        .busy_o  (quant_busy_o),
        .done_o  (quant_done_o),

        // Raw Q read interface
        .q_raw_rd_token_o   (quant_q_rd_token),
        .q_raw_rd_feature_o (quant_q_rd_feature),
        .q_raw_data_i       (q_data_o),

        // Raw K read interface
        .k_raw_rd_token_o   (quant_k_rd_token),
        .k_raw_rd_feature_o (quant_k_rd_feature),
        .k_raw_data_i       (k_data_o),

        // Quantized Q8 read interface
        .q8_rd_token_i   (q8_rd_token_i),
        .q8_rd_feature_i (q8_rd_feature_i),
        .q8_data_o       (q8_data_o),

        // Quantized K8 read interface
        .k8_rd_token_i   (k8_rd_token_i),
        .k8_rd_feature_i (k8_rd_feature_i),
        .k8_data_o       (k8_data_o),

        // Scaling factors
        .q_shift_o (q_shift_o),
        .k_shift_o (k_shift_o)
    );
    
    //==========================================================
    // Real OpenEye accelerator
    //==========================================================

    OpenEye_FPGA u_openeye (

        .clk_i  (clk_i),
        .rst_ni (rst_ni),

        // DMA input
        .data_dma_i   (dma_input_data),
        .enable_dma_i (dma_input_valid),
        .ready_dma_o  (dma_input_ready),

        // DMA output
        .data_dma_o   (dma_output_data),
        .enable_dma_o (dma_output_valid),
        .last_data_o  (dma_output_last),
        .ready_dma_i  (dma_output_ready)
    );

endmodule